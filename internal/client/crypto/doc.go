// Пакет crypto реализует всю криптографическую логику клиента Voldepass.
//
// Архитектура ключей (key-wrapping):
//   - Из мастер-пароля и KDF-соли через Argon2id выводятся два ключа:
//     authKey (для аутентификации) и encKey (для оборачивания dataKey).
//   - dataKey — случайный 256-битный ключ, шифрующий записи через AES-256-GCM.
//   - dataKey никогда не передаётся по сети в открытом виде; на сервер уходит
//     только wrappedDataKey = AES-GCM(encKey, dataKey).
//   - При смене мастер-пароля достаточно переобернуть dataKey — перешифровывать
//     все записи не нужно.
//
// Аутентификация (challenge-response):
//   - authKey используется только для вычисления HMAC-SHA256(authKey, serverNonce).
//   - authKey по сети не передаётся; сервер хранит верификатор.

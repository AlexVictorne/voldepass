-- Синхронизация (GET /sync?since=) требует, чтобы version был глобальным
-- монотонным курсором: клиент запоминает максимальный увиденный version и
-- запрашивает "все записи с version > since". Прежняя схема нумеровала версию
-- ЛОКАЛЬНО на каждую запись (INSERT ... VALUES (..., 1, ...) — у каждой новой
-- записи version начинался с 1), из-за чего вторая и последующие новые записи
-- получали тот же version=1, что и первая, и не проходили фильтр "version > since"
-- при последующих Pull — клиент их просто не видел.
CREATE SEQUENCE IF NOT EXISTS records_version_seq;

-- Прогреваем последовательность на случай, если в таблице уже есть данные
-- (например, применение этой миграции на существующей БД), чтобы новые
-- версии не начинались заново с 1 и не конфликтовали с уже выданными.
-- is_called=false гарантирует, что следующий nextval() вернёт ровно
-- (текущий максимум + 1), а не (текущий максимум + 2); при пустой таблице
-- это корректно даёт 1, а не 0 (минимально допустимое значение sequence — 1).
SELECT setval('records_version_seq', COALESCE((SELECT MAX(version) FROM records), 0) + 1, false);
